
-- 1. Tabela base: usuarios (Estratégia InheritanceType.JOINED)
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento VARCHAR(255) NOT NULL UNIQUE,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    telefone VARCHAR(255),
    tipo_usuario VARCHAR(50) NOT NULL,
    tipo_pessoa VARCHAR(50) NOT NULL,
    -- Campos embutidos (@Embedded Endereco)
    endereco_cep VARCHAR(255),
    endereco_logradouro VARCHAR(255),
    endereco_numero VARCHAR(255),
    endereco_complemento VARCHAR(255),
    endereco_bairro VARCHAR(255),
    endereco_cidade VARCHAR(255),
    endereco_estado VARCHAR(255)
);

-- 2. Tabela de especialização: doadores
CREATE TABLE doadores (
    id BIGINT NOT NULL PRIMARY KEY,
    CONSTRAINT fk_doadores_usuario FOREIGN KEY (id) REFERENCES usuarios (id) ON DELETE CASCADE
);

-- 3. Tabela de especialização: transportadores
CREATE TABLE transportadores (
    id BIGINT NOT NULL PRIMARY KEY,
    CONSTRAINT fk_transportadores_usuario FOREIGN KEY (id) REFERENCES usuarios (id) ON DELETE CASCADE
);

-- 4. Tabela de especialização: receptores
CREATE TABLE receptores (
    id BIGINT NOT NULL PRIMARY KEY,
    -- Campos embutidos com override (@Embedded Endereco enderecoOrganizacao)
    receptor_cep VARCHAR(255),
    receptor_logradouro VARCHAR(255),
    receptor_numero VARCHAR(255),
    receptor_complemento VARCHAR(255),
    receptor_bairro VARCHAR(255),
    receptor_cidade VARCHAR(255),
    receptor_estado VARCHAR(255),
    CONSTRAINT fk_receptores_usuario FOREIGN KEY (id) REFERENCES usuarios (id) ON DELETE CASCADE
);

-- 5. Tabela de tokens de autenticação: refresh_tokens
CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    usuario_id BIGINT NOT NULL,
    expira_em TIMESTAMP WITH TIME ZONE NOT NULL,
    revogado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_refresh_tokens_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);

-- 6. Tabela de ofertas de doação: ofertas_doacao
CREATE TABLE ofertas_doacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doador_id BIGINT NOT NULL,
    situacao VARCHAR(50) NOT NULL,
    -- Campos embutidos (@Embedded Endereco localRetirada)
    cep VARCHAR(255),
    logradouro VARCHAR(255),
    numero VARCHAR(255),
    complemento VARCHAR(255),
    bairro VARCHAR(255),
    cidade VARCHAR(255),
    estado VARCHAR(255),
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_ofertas_doacao_doador FOREIGN KEY (doador_id) REFERENCES doadores (id)
);

-- 7. Tabela de itens da doação: itens_doacao
CREATE TABLE itens_doacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(500),
    tipo_item_doacao VARCHAR(50) NOT NULL,
    tipo_unidade SMALLINT NOT NULL,
    quantidade FLOAT8 NOT NULL,
    oferta_id BIGINT NOT NULL,
    CONSTRAINT fk_itens_doacao_oferta FOREIGN KEY (oferta_id) REFERENCES ofertas_doacao (id) ON DELETE CASCADE
);

-- Índices para chaves estrangeiras para otimização de performance
CREATE INDEX idx_refresh_tokens_usuario_id ON refresh_tokens (usuario_id);
CREATE INDEX idx_ofertas_doacao_doador_id ON ofertas_doacao (doador_id);
CREATE INDEX idx_itens_doacao_oferta_id ON itens_doacao (oferta_id);

