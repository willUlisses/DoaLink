CREATE TABLE reservas_entrega (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_id BIGINT NOT NULL,
    receptor_id BIGINT NOT NULL,
    disponibilidade_id BIGINT,
    precisa_transporte BOOLEAN NOT NULL,
    situacao VARCHAR(40) NOT NULL,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_reservas_oferta FOREIGN KEY (oferta_id) REFERENCES ofertas_doacao (id),
    CONSTRAINT fk_reservas_receptor FOREIGN KEY (receptor_id) REFERENCES receptores (id),
    CONSTRAINT fk_reservas_disponibilidade FOREIGN KEY (disponibilidade_id) REFERENCES disponibilidades_transporte (id)
);

CREATE UNIQUE INDEX uk_reserva_entrega_oferta_ativa
    ON reservas_entrega (oferta_id)
    WHERE situacao <> 'CANCELADA';

CREATE INDEX idx_reservas_receptor_criado
    ON reservas_entrega (receptor_id, criado_em DESC);

CREATE INDEX idx_reservas_disponibilidade_situacao
    ON reservas_entrega (disponibilidade_id, situacao);

CREATE INDEX idx_reservas_situacao_criado
    ON reservas_entrega (situacao, criado_em DESC);

