-- Converte os ordinais históricos de TipoUnidade para os nomes atuais do enum.
ALTER TABLE itens_doacao ALTER COLUMN tipo_unidade TYPE VARCHAR(50)
    USING CASE tipo_unidade
        WHEN 0 THEN 'SEMUNIDADE'
        WHEN 1 THEN 'KG'
        WHEN 2 THEN 'T'
        WHEN 3 THEN 'CAIXAS'
        WHEN 4 THEN 'CESTAS_BASICAS'
        WHEN 5 THEN 'ML'
        WHEN 6 THEN 'G'
        ELSE NULL
    END;

ALTER TABLE itens_doacao ALTER COLUMN oferta_id DROP NOT NULL;
ALTER TABLE itens_doacao ADD COLUMN necessidade_id BIGINT;

CREATE TABLE necessidades_doacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receptor_id BIGINT NOT NULL,
    cep VARCHAR(255) NOT NULL,
    logradouro VARCHAR(255) NOT NULL,
    numero VARCHAR(255) NOT NULL,
    complemento VARCHAR(255),
    bairro VARCHAR(255) NOT NULL,
    cidade VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    situacao VARCHAR(30) NOT NULL DEFAULT 'ABERTA',
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_necessidades_doacao_receptor FOREIGN KEY (receptor_id) REFERENCES receptores (id)
);

ALTER TABLE itens_doacao ADD CONSTRAINT fk_itens_doacao_necessidade
    FOREIGN KEY (necessidade_id) REFERENCES necessidades_doacao (id) ON DELETE CASCADE;
ALTER TABLE itens_doacao ADD CONSTRAINT ck_itens_doacao_vinculo
    CHECK ((oferta_id IS NOT NULL AND necessidade_id IS NULL)
        OR (oferta_id IS NULL AND necessidade_id IS NOT NULL));

CREATE INDEX idx_necessidades_receptor_criado ON necessidades_doacao (receptor_id, criado_em DESC);
CREATE INDEX idx_necessidades_situacao_criado ON necessidades_doacao (situacao, criado_em DESC);
CREATE INDEX idx_itens_doacao_necessidade_id ON itens_doacao (necessidade_id);
