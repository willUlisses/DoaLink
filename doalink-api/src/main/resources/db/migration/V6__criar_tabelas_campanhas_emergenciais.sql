CREATE TABLE campanhas_emergenciais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receptor_id BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(1000),
    situacao VARCHAR(30) NOT NULL DEFAULT 'ATIVA',
    cep VARCHAR(255) NOT NULL,
    logradouro VARCHAR(255) NOT NULL,
    numero VARCHAR(255) NOT NULL,
    complemento VARCHAR(255),
    bairro VARCHAR(255) NOT NULL,
    cidade VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_campanhas_emergenciais_receptor FOREIGN KEY (receptor_id) REFERENCES receptores (id)
);

CREATE TABLE itens_campanha (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campanha_id BIGINT NOT NULL,
    tipo_item_doacao VARCHAR(50) NOT NULL,
    tipo_unidade VARCHAR(50) NOT NULL,
    quantidade FLOAT8 NOT NULL,
    descricao VARCHAR(500),
    CONSTRAINT fk_itens_campanha_campanha FOREIGN KEY (campanha_id) REFERENCES campanhas_emergenciais (id) ON DELETE CASCADE
);

CREATE INDEX idx_campanhas_receptor_criado ON campanhas_emergenciais (receptor_id, criado_em DESC);
CREATE INDEX idx_campanhas_situacao_criado ON campanhas_emergenciais (situacao, criado_em DESC);
CREATE INDEX idx_itens_campanha_id ON itens_campanha (campanha_id);
