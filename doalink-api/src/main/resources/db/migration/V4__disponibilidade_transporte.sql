CREATE TABLE disponibilidades_transporte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transportador_id BIGINT NOT NULL,
    tipo_veiculo VARCHAR(50) NOT NULL,
    capacidade FLOAT8 NOT NULL,
    capacidade_restante FLOAT8 NOT NULL,
    tipo_unidade VARCHAR(50) NOT NULL,
    origem_cep VARCHAR(255) NOT NULL,
    origem_logradouro VARCHAR(255) NOT NULL,
    origem_numero VARCHAR(255) NOT NULL,
    origem_complemento VARCHAR(255),
    origem_bairro VARCHAR(255) NOT NULL,
    origem_cidade VARCHAR(255) NOT NULL,
    origem_estado VARCHAR(255) NOT NULL,
    data_disponivel DATE NOT NULL,
    horario_disponivel TIME WITHOUT TIME ZONE,
    situacao VARCHAR(30) NOT NULL DEFAULT 'DISPONIVEL',
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_disponibilidades_transportador FOREIGN KEY (transportador_id) REFERENCES transportadores (id),
    CONSTRAINT ck_disponibilidades_capacidade CHECK (capacidade > 0),
    CONSTRAINT ck_disponibilidades_capacidade_restante CHECK (capacidade_restante >= 0 AND capacidade_restante <= capacidade)
);

CREATE UNIQUE INDEX uk_disponibilidade_transportador_data_ativa
    ON disponibilidades_transporte (transportador_id, data_disponivel)
    WHERE situacao IN ('DISPONIVEL', 'RESERVADA');

CREATE INDEX idx_disponibilidades_transportador_data
    ON disponibilidades_transporte (transportador_id, data_disponivel ASC, criado_em DESC);

CREATE INDEX idx_disponibilidades_situacao_data
    ON disponibilidades_transporte (situacao, data_disponivel);
