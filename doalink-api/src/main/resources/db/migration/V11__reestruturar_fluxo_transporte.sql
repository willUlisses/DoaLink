-- 1. Status da conta do transportador
ALTER TABLE transportadores
    ADD COLUMN situacao VARCHAR(30) NOT NULL DEFAULT 'ATIVO',
    ADD COLUMN suspenso_em TIMESTAMP WITHOUT TIME ZONE,
    ADD COLUMN motivo_suspensao VARCHAR(500);

-- 2. Vínculo direto do transportador na reserva de entrega e timestamps de auditoria do fluxo
ALTER TABLE reservas_entrega
    ADD COLUMN transportador_id BIGINT,
    ADD COLUMN aceito_em TIMESTAMP WITHOUT TIME ZONE,
    ADD COLUMN autorizado_em TIMESTAMP WITHOUT TIME ZONE,
    ADD COLUMN retirada_confirmada_em TIMESTAMP WITHOUT TIME ZONE,
    ADD COLUMN entrega_confirmada_em TIMESTAMP WITHOUT TIME ZONE;

ALTER TABLE reservas_entrega
    ADD CONSTRAINT fk_reservas_transportador FOREIGN KEY (transportador_id) REFERENCES transportadores (id);

-- 3. Migração segura de vínculos existentes antes da remoção de disponibilidades_transporte
UPDATE reservas_entrega r
SET transportador_id = d.transportador_id,
    aceito_em = COALESCE(r.atualizado_em, r.criado_em)
FROM disponibilidades_transporte d
WHERE r.disponibilidade_id = d.id
  AND r.transportador_id IS NULL;

UPDATE reservas_entrega
SET situacao = 'AGUARDANDO_AUTORIZACAO_DOADOR'
WHERE situacao = 'TRANSPORTE_VINCULADO';

-- 4. Remoção da estrutura de disponibilidade de transporte
DROP INDEX IF EXISTS idx_reservas_disponibilidade_situacao;
ALTER TABLE reservas_entrega DROP CONSTRAINT IF EXISTS fk_reservas_disponibilidade;
ALTER TABLE reservas_entrega DROP COLUMN IF EXISTS disponibilidade_id;
DROP TABLE IF EXISTS disponibilidades_transporte;

CREATE INDEX idx_reservas_transportador_situacao
    ON reservas_entrega (transportador_id, situacao, criado_em DESC);

-- 5. Códigos de segurança de retirada e entrega (armazenados com hash SHA-256 + salt)
CREATE TABLE codigos_transporte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL,
    transportador_id BIGINT NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    codigo_hash VARCHAR(64) NOT NULL,
    codigo_salt VARCHAR(64) NOT NULL,
    expira_em TIMESTAMP WITHOUT TIME ZONE,
    utilizado BOOLEAN NOT NULL DEFAULT FALSE,
    invalidado BOOLEAN NOT NULL DEFAULT FALSE,
    bloqueado BOOLEAN NOT NULL DEFAULT FALSE,
    tentativas INTEGER NOT NULL DEFAULT 0,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    utilizado_em TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_codigos_transporte_reserva FOREIGN KEY (reserva_id) REFERENCES reservas_entrega (id) ON DELETE CASCADE,
    CONSTRAINT fk_codigos_transporte_transportador FOREIGN KEY (transportador_id) REFERENCES transportadores (id)
);

CREATE INDEX idx_codigos_transporte_reserva_tipo
    ON codigos_transporte (reserva_id, tipo, criado_em DESC);

CREATE INDEX idx_codigos_transporte_entrega_expiracao
    ON codigos_transporte (tipo, utilizado, invalidado, expira_em);

-- 6. Trilha de eventos e auditoria do transporte
CREATE TABLE eventos_transporte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL,
    usuario_id BIGINT,
    tipo_evento VARCHAR(60) NOT NULL,
    detalhes VARCHAR(500) NOT NULL,
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_eventos_transporte_reserva FOREIGN KEY (reserva_id) REFERENCES reservas_entrega (id) ON DELETE CASCADE,
    CONSTRAINT fk_eventos_transporte_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE INDEX idx_eventos_transporte_reserva_criado
    ON eventos_transporte (reserva_id, criado_em ASC);

-- 7. Ocorrências de expiração para investigação administrativa
CREATE TABLE ocorrencias_transporte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL UNIQUE,
    oferta_id BIGINT NOT NULL,
    transportador_id BIGINT NOT NULL,
    doador_id BIGINT NOT NULL,
    receptor_id BIGINT NOT NULL,
    motivo VARCHAR(120) NOT NULL,
    descricao VARCHAR(1000) NOT NULL,
    situacao VARCHAR(40) NOT NULL DEFAULT 'PENDENTE_INVESTIGACAO',
    aceito_em TIMESTAMP WITHOUT TIME ZONE,
    autorizado_em TIMESTAMP WITHOUT TIME ZONE,
    retirada_confirmada_em TIMESTAMP WITHOUT TIME ZONE,
    prazo_entrega_expirado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    tentativas_validacao_entrega INTEGER NOT NULL DEFAULT 0,
    observacoes_resolucao VARCHAR(1000),
    criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    resolvido_em TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT fk_ocorrencias_reserva FOREIGN KEY (reserva_id) REFERENCES reservas_entrega (id),
    CONSTRAINT fk_ocorrencias_oferta FOREIGN KEY (oferta_id) REFERENCES ofertas_doacao (id),
    CONSTRAINT fk_ocorrencias_transportador FOREIGN KEY (transportador_id) REFERENCES transportadores (id),
    CONSTRAINT fk_ocorrencias_doador FOREIGN KEY (doador_id) REFERENCES doadores (id),
    CONSTRAINT fk_ocorrencias_receptor FOREIGN KEY (receptor_id) REFERENCES receptores (id)
);

CREATE INDEX idx_ocorrencias_transportador_situacao
    ON ocorrencias_transporte (transportador_id, situacao, criado_em DESC);
